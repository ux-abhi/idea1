import Foundation

/// One copied thing. Text and links are kept; images keep a small PNG.
public struct ClipItem: Codable, Identifiable, Equatable, Sendable {
    public enum Kind: String, Codable, Sendable { case text, link, image }

    public let id: UUID
    public let kind: Kind
    public let text: String
    public let image: Data?
    public let copiedAt: Date

    public init(kind: Kind, text: String, image: Data? = nil, copiedAt: Date = .now) {
        id = UUID()
        self.kind = kind
        self.text = text
        self.image = image
        self.copiedAt = copiedAt
    }

    /// Text that is a single web address counts as a link.
    public static func text(_ string: String, at date: Date = .now) -> ClipItem {
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        let isLink = !trimmed.contains(" ") && (URL(string: trimmed)?.scheme.map { ["http", "https"].contains($0) } ?? false)
        return ClipItem(kind: isLink ? .link : .text, text: string, copiedAt: date)
    }
}

/// Clipboard history (ARCHITECTURE §31): newest first, at most `limit`, a repeat moves to the top. Never leaves the Mac.
public struct ClipboardHistory: Codable, Equatable, Sendable {
    public private(set) var items: [ClipItem] = []
    public static let limit = 50

    public init(items: [ClipItem] = []) {
        self.items = Array(items.prefix(Self.limit))
    }

    public mutating func add(_ item: ClipItem) {
        guard item.kind == .image || !item.text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        items.removeAll { $0.kind != .image && $0.text == item.text }
        items.insert(item, at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
    }

    public mutating func remove(_ id: UUID) { items.removeAll { $0.id == id } }
    public mutating func clear() { items.removeAll() }

    public func search(_ query: String) -> [ClipItem] {
        let q = query.trimmingCharacters(in: .whitespaces)
        return q.isEmpty ? items : items.filter { $0.text.localizedCaseInsensitiveContains(q) }
    }

    /// Password managers mark secrets on the pasteboard (nspasteboard.org conventions); those are never recorded.
    public static func shouldRecord(types: [String]) -> Bool {
        let skip: Set<String> = [
            "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
            "com.agilebits.onepassword", "com.apple.is-remote-clipboard.concealed",
        ]
        return !types.contains(where: skip.contains)
    }
}
